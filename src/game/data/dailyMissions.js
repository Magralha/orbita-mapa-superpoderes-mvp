export function missionForDate(date = new Date()) {
  const start = Date.UTC(2026, 0, 1);
  const day = Math.floor((Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - start) / 86400000);
  const index = ((day % dailyMissions.length) + dailyMissions.length) % dailyMissions.length;
  return dailyMissions[index];
}

export function missionsByTerritory(territory) {
  return dailyMissions.filter((mission) => mission.territory === territory);
}
